# -*- coding: utf-8 -*-
"""ПАМЯТЬ НА СТОРОНЕ TELEGRAM — чтобы канал не молчал, пока нет базы.

Зачем это есть.

Правило проекта: любое действие, которое продукт делает сам и наружу,
обязано иметь память, переживающую перезапуск. Нет памяти — нет действия.
16 августа нарушение этого правила стоило семнадцати копий одного поста
в канале с четырьмя подписчиками.

Память бота живёт в Postgres. Пока `DATABASE_URL` не задан, её нет вовсе:
на бесплатном тарифе Render диск стирается при каждом пробуждении сервиса,
и файл с отметкой «этот пост уже публиковали» исчезает вместе с ним.
Поэтому канал — единственный работающий источник людей — сейчас молчит.

Но одно место, переживающее наши перезапуски, у бота всё-таки есть:
сервера самого Telegram. Токен туда уже есть, и бот уже пишет туда список
своих команд. Список команд можно задать ОТДЕЛЬНО ДЛЯ ОДНОГО ЧАТА
(`scope` = `chat`). Команды, заданные для канала, не видит никто: в канале
никто не набирает боту команд, там даже поля ввода нет. Зато они лежат у
Telegram, читаются обратно и переживают что угодно с нашей стороны.

Это и есть хранилище: имя команды — ключ, описание — значение.

**Чем это НЕ является.** Это память на несколько отметок, а не база.
Подписчиков, события и паузы между письмами сюда не положить: там сотни
записей и личные данные людей. Поэтому она открывает ровно одно — посты
в канал. Личные сообщения по-прежнему требуют `DATABASE_URL`, и там
правило не смягчается ни на волос: за повтор в канале отписываются, а за
повтор в личных бота блокируют, и это навсегда.

**Почему ей можно верить.** Не на слово. При запуске бот пишет сюда
случайную метку и читает её обратно. Совпало — память работает, канал
может публиковать. Не совпало, не ответило, ответило старым значением —
памяти нет, и канал молчит ровно так же, как молчал. Проверка идёт на
боевом, при каждом запуске, и не зависит от того, что мы думаем про этот
API: он либо доказал, что помнит, либо нет.

**Это временная опора, а не замена базе.** `DATABASE_URL` нужен всё так же
и по трём другим причинам сразу: подписчики, события и оповещения. Здесь
закрыт только канал — потому что он единственный, кто приводит людей, и
каждый день его молчания стоит подписчиков, которых не будет.
"""
import random
import re

# Telegram: имя команды — до 32 знаков, только строчные латинские буквы,
# цифры и подчёркивание. Описание — от 1 до 256 знаков. Наши ключи
# (`post_den`, `post_nedelya`, `kurs_osveshchen`, `svodka`) и наши
# значения (даты, номера недель) в эти рамки укладываются с запасом, но
# проверять всё равно надо: ключ, не прошедший правило, Telegram отвергнет
# ЦЕЛИКОМ ВСЮ запись, то есть заодно потеряет и остальные отметки.
IMYA_KLUCHA = re.compile(r"^[a-z0-9_]{1,32}$")
DLINA_ZNACHENIYA = 256

# Ключ, под которым лежит метка проверки. Занимает место в списке
# намеренно: по нему видно, что память проверялась, и когда.
KLUCH_PROVERKI = "proverka_pamyati"


def prigoden(kluch, znachenie):
    """Ляжет ли такая пара в хранилище Telegram."""
    return bool(IMYA_KLUCHA.match(str(kluch))) and bool(str(znachenie))


class PamyatTelegrama(object):
    """Ключ-значение на серверах Telegram, в списке команд канала."""

    def __init__(self, vyzov, kanal):
        self.vyzov = vyzov
        self.kanal = kanal
        self.rabotaet = False
        # Последнее, что мы точно знаем. Нужно на случай, когда записать
        # надо, а свежее чтение не прошло: писать поверх пустоты нельзя —
        # это стёрло бы остальные отметки и вернуло нас к повторным постам.
        self.zerkalo = {}

    # ── разговор с Telegram ──────────────────────────────────────────

    def _oblast(self):
        return {"type": "chat", "chat_id": self.kanal}

    def vse(self):
        """Все отметки. **None означает «не смогли прочитать»**.

        Разница принципиальная. Пустой словарь читается как «ничего ещё не
        публиковали» и разрешает пост. Молчание сети — не разрешение:
        именно из такого «не знаю, значит можно» и выходят повторы.
        """
        otvet = self.vyzov("getMyCommands", {"scope": self._oblast()})
        if not otvet or not otvet.get("ok"):
            return None
        spisok = otvet.get("result")
        if not isinstance(spisok, list):
            return None

        dannye = {}
        for zapis in spisok:
            if isinstance(zapis, dict) and zapis.get("command"):
                dannye[str(zapis["command"])] = str(zapis.get("description") or "")
        self.zerkalo = dict(dannye)
        return dannye

    def _zapisat_vse(self, dannye):
        komandy = [{"command": str(k), "description": str(z)[:DLINA_ZNACHENIYA]}
                   for k, z in sorted(dannye.items()) if prigoden(k, z)]
        otvet = self.vyzov("setMyCommands",
                           {"scope": self._oblast(), "commands": komandy})
        if not otvet or not otvet.get("ok"):
            return False
        self.zerkalo = {str(k["command"]): str(k["description"]) for k in komandy}
        return True

    # ── работа ───────────────────────────────────────────────────────

    def podnyat(self):
        """Проверяет память боем: пишет случайную метку и читает обратно.

        Возвращает True, только если Telegram отдал ровно то, что мы
        записали. Всё остальное — «памяти нет», и это честный ответ:
        непроверенное не считается пройденным.
        """
        if not self.kanal:
            return False

        bylo = self.vse()
        if bylo is None:
            print("[память] Telegram не отдал отметки канала — памяти нет, "
                  "канал молчит", flush=True)
            return False

        metka = "proba-%d" % random.randrange(10 ** 9)
        dannye = dict(bylo)
        dannye[KLUCH_PROVERKI] = metka

        if not self._zapisat_vse(dannye):
            print("[память] Telegram не принял отметки канала — памяти нет, "
                  "канал молчит", flush=True)
            return False

        stalo = self.vse()
        if stalo is None:
            print("[память] записали, но прочитать обратно не смогли — "
                  "памяти нет, канал молчит", flush=True)
            return False
        if stalo.get(KLUCH_PROVERKI) != metka:
            # Сюда попадаем, если Telegram отдал старое значение. Тогда
            # «уже публиковали» тоже читалось бы старым, а это ровно тот
            # случай, ради которого всё и затевалось.
            print("[память] Telegram вернул не то, что записали — памяти нет, "
                  "канал молчит", flush=True)
            return False

        # Проверка не должна съедать чужие отметки: то, что лежало до неё,
        # обязано лежать и после. Иначе каждый перезапуск стирал бы память
        # ровно тем действием, которое её проверяет.
        poteryano = [k for k in bylo if k != KLUCH_PROVERKI and k not in stalo]
        if poteryano:
            print("[память] проверка потеряла отметки %s — не доверяю"
                  % ", ".join(sorted(poteryano)), flush=True)
            return False

        self.rabotaet = True
        print("[память] отметки о постах лежат у Telegram и читаются обратно "
              "— канал может публиковать без DATABASE_URL", flush=True)
        return True

    def zapisat(self, kluch, znachenie):
        """Запоминает значение. False — не запомнилось, повтор возможен."""
        znachenie = str(znachenie)[:DLINA_ZNACHENIYA]
        if not prigoden(kluch, znachenie):
            print("[память] ключ «%s» не годится для хранилища Telegram"
                  % kluch, flush=True)
            return False

        dannye = self.vse()
        if dannye is None:
            # Свежее чтение не прошло — пишем поверх последнего известного.
            # Так теряется в худшем случае отметка, поставленная другим
            # процессом, а процесс у нас один.
            dannye = dict(self.zerkalo)
        dannye[str(kluch)] = znachenie
        return self._zapisat_vse(dannye)
