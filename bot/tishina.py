"""МОЛЧИТ ЛИ КАНАЛ — правило, по которому срабатывает тревога.

Отдельным файлом и чистыми функциями — чтобы проверялось. По этому
правилу сторож заводит задачу и шлёт Семёну письмо; правило, которое
краснеет зря, обесценивает и себя, и все остальные письма сторожа. А
проверить его на живом канале нельзя: нужный случай там бывает раз в
месяц и длится девять дней.

ЗАЧЕМ ВООБЩЕ. Канал — единственное, что приводит людей в продукт. С 21
по 30 августа он молчал девять суток подряд, пока лежал Render, и
заметили это по календарю, а не по тревоге. С сентября у утреннего поста
две двери — бот и работа GitHub, — и тем нужнее знать, что закрыты обе:
вторая может молча не заработать, и узнали бы мы об этом снова через
неделю по пустой ленте.

ПОЧЕМУ НЕ ПО ЧИСЛУ ДНЕЙ МОЛЧАНИЯ. ЦБ не публикует курс по выходным и в
праздники, и в такие дни канал молчит ПРАВИЛЬНО: молчание лучше повтора,
это правило проекта. Счётчик дней краснел бы каждые выходные, а в
Узбекистане бывают и трёхдневные праздники.

ПО ЧЕМУ СУДИМ. По тому, освещён ли курс. Берём даты публикаций ЦБ,
которые новее последнего поста:

    ни одной      — канал в порядке, сказать ему нечего;
    одна          — сегодня ещё успеется. Бот пишет с 9:00 по Ташкенту,
                    работа GitHub в 11:00 и 15:00. До закрытия последней
                    двери это жёлтое, а не красное;
    две и больше  — молчат обе двери, и это уже поломка.

Даты — строками вида `2026-09-03`, и сравниваются как строки: у ISO это
то же самое, что сравнение дат, только без разбора и без часовых поясов,
которых здесь и не должно быть.
"""

# Час, после которого сегодняшнее молчание перестаёт быть ожиданием.
# Работа GitHub пробует в 11:00 и 15:00 по Ташкенту; к четырём последняя
# дверь закрыта, и если поста нет — его уже не будет.
CHAS_POSLEDNEY_DVERI = 16

ZELYONOE = "zelyonoe"
ZHOLTOE = "zholtoe"
KRASNOE = "krasnoe"


def ne_osveshcheno(posledniy_post, daty_kursa):
    """Даты публикаций ЦБ, о которых канал ещё не сказал.

    `posledniy_post` — ташкентская дата последнего сообщения в канале,
    строкой; пусто означает, что в канале нет ни одного сообщения, и
    тогда не освещено всё.
    """
    daty = {str(d)[:10] for d in (daty_kursa or []) if d}
    if not posledniy_post:
        return sorted(daty)
    return sorted(d for d in daty if d > str(posledniy_post)[:10])


def sudit(posledniy_post, daty_kursa, chas_uz):
    """(цвет, список неосвещённых дат). Час — ташкентский, 0–23.

    Жёлтое при пустых датах курса — не зелёное: «не с чем сравнить» это
    не «всё хорошо». Ровно та же разница, что между «записи нет» и
    «прочитать не удалось» в хранилище, и цена ошибки та же — молчащий
    канал, объявленный исправным.
    """
    otstalo = ne_osveshcheno(posledniy_post, daty_kursa)

    if not otstalo:
        # Дат курса нет вовсе — сравнивать не с чем, и молчать об этом
        # нельзя: не спросили и не отстали — разные вещи.
        return (ZHOLTOE if not daty_kursa else ZELYONOE), []

    if len(otstalo) == 1 and int(chas_uz) < CHAS_POSLEDNEY_DVERI:
        return ZHOLTOE, otstalo

    return KRASNOE, otstalo
